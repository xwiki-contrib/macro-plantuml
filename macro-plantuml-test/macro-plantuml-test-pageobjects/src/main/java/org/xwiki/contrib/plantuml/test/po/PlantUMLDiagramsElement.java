package org.xwiki.contrib.plantuml.test.po;

import java.util.List;
import java.util.stream.Collectors;

import org.openqa.selenium.By;
import org.openqa.selenium.WebElement;
import org.xwiki.test.ui.po.BaseElement;

/**
 * Represents the diagrams generated by the PlantUML macros found in the content of the current page, or in the
 * comments displayed on it.
 *
 * @version $Id$
 * @since 2.5
 */
public class PlantUMLDiagramsElement extends BaseElement
{
    private static final String CONTENT_SELECTOR = "#xwikicontent";

    private static final String COMMENTS_SELECTOR = "#commentscontent .commentcontent";

    private static final String ERROR_DESCRIPTION_CLASS = "xwikirenderingerrordescription";

    // The error details are displayed when clicking on the error message.
    private static final By ERROR_DESCRIPTION =
        By.xpath("following-sibling::*[1][contains(@class, '" + ERROR_DESCRIPTION_CLASS + "')]");

    private static final String TEXT_CONTENT = "textContent";

    private final By images;

    private final By svgDiagrams;

    private final By textDiagrams;

    private final By errors;

    /**
     * Waits until all the PlantUML macros of the current page content have been rendered.
     */
    public PlantUMLDiagramsElement()
    {
        this(CONTENT_SELECTOR);
    }

    private PlantUMLDiagramsElement(String containerSelector)
    {
        this.images = By.cssSelector(containerSelector + " img");
        this.svgDiagrams = By.cssSelector(containerSelector + " svg");
        // Exclude the stack traces of the errors, which are also displayed in a "pre" element.
        this.textDiagrams =
            By.cssSelector(containerSelector + " div:not(." + ERROR_DESCRIPTION_CLASS + ") > pre");
        this.errors = By.cssSelector(containerSelector + " .xwikirenderingerror");

        // The PlantUML macro is rendered asynchronously: a placeholder is first displayed and then replaced by the
        // diagram once it's been generated.
        By asyncPlaceholder = By.cssSelector(containerSelector + " .xwiki-async");
        getDriver().waitUntilCondition(driver -> !getDriver().hasElementWithoutWaiting(asyncPlaceholder));
    }

    /**
     * Waits until all the PlantUML macros of the comments displayed on the current page have been rendered.
     *
     * @return the diagrams found in the comments displayed on the current page
     * @since 2.5
     */
    public static PlantUMLDiagramsElement inComments()
    {
        return new PlantUMLDiagramsElement(COMMENTS_SELECTOR);
    }

    /**
     * @return the number of diagrams displayed as images (PNG format) that have been successfully loaded by the
     *     browser, i.e. that are not broken images
     */
    public int getDisplayedImageCount()
    {
        List<WebElement> images = getDriver().findElementsWithoutWaiting(this.images);
        getDriver().waitUntilCondition(driver -> images.stream()
            .allMatch(image -> Boolean.TRUE.equals(getDriver().executeScript("return arguments[0].complete;", image))));
        return (int) images.stream()
            .filter(image -> ((Number) getDriver().executeScript("return arguments[0].naturalWidth;", image))
                .intValue() > 0)
            .count();
    }

    /**
     * @return the texts found in each of the diagrams displayed as vector images (SVG format)
     */
    public List<String> getSVGDiagramTexts()
    {
        return getTextContents(this.svgDiagrams);
    }

    /**
     * @return each of the diagrams displayed as ASCII art (TXT format)
     */
    public List<String> getTextDiagrams()
    {
        return getTextContents(this.textDiagrams);
    }

    /**
     * @return the full text (i.e. including the details displayed when clicking on the error) of each of the errors
     *     displayed instead of a diagram
     */
    public List<String> getErrors()
    {
        return getDriver().findElementsWithoutWaiting(this.errors).stream()
            .map(error -> getTextContent(error) + getDriver().findElementsWithoutWaiting(error, ERROR_DESCRIPTION)
                .stream().map(this::getTextContent).collect(Collectors.joining()))
            .toList();
    }

    private List<String> getTextContents(By by)
    {
        return getDriver().findElementsWithoutWaiting(by).stream()
            .map(this::getTextContent)
            .toList();
    }

    private String getTextContent(WebElement element)
    {
        // Use the text content and not the visible text since the error details are hidden by default.
        return element.getAttribute(TEXT_CONTENT);
    }
}
