package org.xwiki.contrib.plantuml.test.po;

import org.openqa.selenium.By;
import org.xwiki.administration.test.po.AdministrationSectionPage;
import org.xwiki.test.ui.po.FormContainerElement;

/**
 * Represents the PlantUML section of the wiki administration.
 *
 * @version $Id$
 * @since 2.5
 */
public class PlantUMLAdministrationSectionPage extends AdministrationSectionPage
{
    private static final String SECTION_ID = "PlantUML";

    private static final String SERVER_FIELD_NAME = "PlantUML.PlantUMLConfigClass_0_server";

    private static final By SERVER_FIELD = By.name(SERVER_FIELD_NAME);

    private static final By FORM = By.xpath("//form[.//input[@name='" + SERVER_FIELD_NAME + "']]");

    /**
     * Default constructor.
     */
    public PlantUMLAdministrationSectionPage()
    {
        super(SECTION_ID);
    }

    /**
     * Opens the PlantUML section of the wiki administration.
     *
     * @return the page object for the PlantUML administration section
     */
    public static PlantUMLAdministrationSectionPage gotoPage()
    {
        AdministrationSectionPage.gotoPage(SECTION_ID);
        return new PlantUMLAdministrationSectionPage();
    }

    /**
     * @return the configured PlantUML Server URL (empty when none is configured)
     */
    public String getServerURL()
    {
        return getForm().getFieldValue(SERVER_FIELD);
    }

    /**
     * @param serverURL the URL of the PlantUML Server to use to generate the diagrams (an empty value means that the
     *     diagrams are generated by XWiki itself)
     */
    public void setServerURL(String serverURL)
    {
        getForm().setFieldValue(SERVER_FIELD, serverURL);
    }

    /**
     * Saves the configuration and waits until it's saved.
     */
    public void save()
    {
        clickSave(true);
    }

    private FormContainerElement getForm()
    {
        return new FormContainerElement(FORM);
    }
}
