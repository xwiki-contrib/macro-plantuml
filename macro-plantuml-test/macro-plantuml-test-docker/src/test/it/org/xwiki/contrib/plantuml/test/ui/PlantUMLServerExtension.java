package org.xwiki.contrib.plantuml.test.ui;

import java.util.Properties;

import org.junit.jupiter.api.extension.BeforeAllCallback;
import org.junit.jupiter.api.extension.ExtensionContext;
import org.testcontainers.containers.GenericContainer;
import org.testcontainers.containers.wait.strategy.Wait;
import org.testcontainers.utility.DockerImageName;
import org.xwiki.test.docker.junit5.TestConfiguration;

/**
 * Starts a PlantUML Server in a Docker container, before XWiki is started, and makes XWiki trust its domain (the
 * PlantUML Macro refuses to use a PlantUML Server whose domain isn't trusted). Must be registered before
 * {@code @UITest}.
 * <p>
 * The PlantUML Server is reached through the port mapped by Docker, on a host that is only known once the container is
 * started (e.g. it's not {@code localhost} when the tests execute inside a Docker container on the CI), hence the
 * dynamic configuration of the trusted domains.
 *
 * @version $Id$
 */
public class PlantUMLServerExtension implements BeforeAllCallback
{
    /**
     * The version of the PlantUML Server, different from the one embedded in the macro, so that the tests can verify
     * that a diagram has been generated by the PlantUML Server and not by XWiki.
     */
    static final String SERVER_VERSION = "1.2025.10";

    private static final int SERVER_PORT = 8080;

    private static final ExtensionContext.Namespace NAMESPACE =
        ExtensionContext.Namespace.create(PlantUMLServerExtension.class);

    private static String serverURL;

    /**
     * @return the URL of the PlantUML Server, as seen by XWiki
     */
    static String getServerURL()
    {
        return serverURL;
    }

    @Override
    public void beforeAll(ExtensionContext context)
    {
        // Start the PlantUML Server only once, even when this extension is registered on several test classes (e.g.
        // on AllIT and on one of its nested test classes). Storing it in the root context store stops it at the end
        // of the test run.
        context.getRoot().getStore(NAMESPACE).getOrComputeIfAbsent(PlantUMLServerResource.class,
            key -> start(context), PlantUMLServerResource.class);
    }

    private PlantUMLServerResource start(ExtensionContext context)
    {
        GenericContainer<?> container =
            new GenericContainer<>(DockerImageName.parse("plantuml/plantuml-server:jetty-v" + SERVER_VERSION))
                .withExposedPorts(SERVER_PORT)
                .waitingFor(Wait.forHttp("/"));
        container.start();

        String host = container.getHost();
        serverURL = String.format("http://%s:%d", host, container.getMappedPort(SERVER_PORT));

        // Contribute the trusted domain to the configuration of the XWiki instance that is started afterwards.
        TestConfiguration testConfiguration = new TestConfiguration();
        Properties properties = new Properties();
        properties.setProperty("xwikiPropertiesAdditionalProperties", "url.trustedDomains=" + host);
        testConfiguration.setProperties(properties);
        context.getRoot().getStore(ExtensionContext.Namespace.GLOBAL).put(TestConfiguration.class, testConfiguration);

        return new PlantUMLServerResource(container);
    }

    private static final class PlantUMLServerResource implements ExtensionContext.Store.CloseableResource
    {
        private final GenericContainer<?> container;

        PlantUMLServerResource(GenericContainer<?> container)
        {
            this.container = container;
        }

        @Override
        public void close()
        {
            this.container.stop();
        }
    }
}
